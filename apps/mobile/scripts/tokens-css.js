// Writes global.css from src/theme/tokens.js. Run: npm run tokens:css -w @legalkart/mobile
//
// Same variables as globalCss() in the token module, with one change for native:
// NativeWind (react-native-css-interop) only reads dark variables from a bare `:root`
// inside `@media (prefers-color-scheme: dark)`. The `:root:not([data-theme="light"])`
// and `:root[data-theme="dark"]` selectors from globalCss() are web-only (they are
// dropped on native), so the app follows the system appearance on every platform.
const fs = require("fs");
const path = require("path");
const { palette } = require("../src/theme/tokens");

const triplet = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
};
const block = (p, indent) =>
  Object.entries(p)
    .map(([k, v]) => `${indent}--lk-${k}: ${triplet(v)};`)
    .join("\n");

const css = `@tailwind base;
@tailwind components;
@tailwind utilities;

/* Generated by scripts/tokens-css.js from src/theme/tokens.js. Do not edit by hand. */
:root {
${block(palette.light, "  ")}
}

@media (prefers-color-scheme: dark) {
  :root {
${block(palette.dark, "    ")}
  }
}
`;

fs.writeFileSync(path.join(__dirname, "..", "global.css"), css);
